"""Turn the project logo into firmware/src/logo.h (RGB565, sized for the Cardputer's 240x135 screen).

  python pipeline/tools/make_logo.py [assets/logo/cardmind_logo_2.jpg]
"""
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets" / "logo" / "cardmind_logo_2.jpg"
OUT = ROOT / "firmware" / "src" / "logo.h"
MAX_W, MAX_H, PAD = 232, 127, 20

im = Image.open(SRC).convert("RGB")
ink = ImageOps.invert(im.convert("L")).point(lambda v: 255 if v > 40 else 0)  # non-white pixels
x0, y0, x1, y1 = ink.getbbox()
im = im.crop((max(0, x0 - PAD), max(0, y0 - PAD), min(im.width, x1 + PAD), min(im.height, y1 + PAD)))
s = min(MAX_W / im.width, MAX_H / im.height)
im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
w, h = im.size
px = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in im.getdata()]
rows = ["    " + ", ".join("0x%04X" % v for v in px[i:i + 16]) + "," for i in range(0, len(px), 16)]
OUT.write_text(
    f"// CardMind boot logo ({SRC.name}), RGB565, generated by pipeline/tools/make_logo.py.\n"
    "#pragma once\n#include <stdint.h>\n\n"
    f"#define LOGO_W {w}\n#define LOGO_H {h}\n\n"
    "static const uint16_t LOGO_RGB565[LOGO_W * LOGO_H] = {\n" + "\n".join(rows) + "\n};\n")
print(f"wrote {OUT}: {w}x{h}, {len(px) * 2} bytes of flash")
